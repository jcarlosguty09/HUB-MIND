import test from 'node:test';
import assert from 'node:assert/strict';
import {filterCheckins, validateAction, buildAction} from './reconciliation-logic.mjs';
const manual={id:'a',manual_name:'Moi',is_manual:true,zk_user_id:null,device_sn:'D1'};
const bio={id:'b',manual_name:null,is_manual:false,zk_user_id:'84',device_sn:'D2'};
const members=[{id:'u1',full_name:'Moi'}];
const base={selected:manual,busy:false,decision:'link_member',targetUserId:'u1',reason:'Confirmado en recepción',members};
test('filtro manual',()=>assert.deepEqual(filterCheckins([manual,bio],'','manual'),[manual]));
test('filtro biométrico',()=>assert.deepEqual(filterCheckins([manual,bio],'','biometric'),[bio]));
test('busca nombre y PIN',()=>{assert.deepEqual(filterCheckins([manual,bio],'moi','all'),[manual]);assert.deepEqual(filterCheckins([manual,bio],'84','all'),[bio]);});
test('no guarda sin motivo',()=>assert.match(validateAction({...base,reason:'  '}),/evidencia/));
test('no guarda con motivo demasiado corto',()=>assert.match(validateAction({...base,reason:'ok'}),/mínimo/));
test('no vincula sin usuario',()=>assert.match(validateAction({...base,targetUserId:''}),/Selecciona/));
test('no vincula usuario ajeno a lista',()=>assert.match(validateAction({...base,targetUserId:'other'}),/autorizada/));
test('evita doble submit',()=>assert.match(validateAction({...base,busy:true}),/no disponible/));
test('vinculación válida',()=>assert.equal(validateAction(base),null));
test('visitante no requiere usuario',()=>assert.equal(validateAction({...base,decision:'visitor',targetUserId:''}),null));
test('acción de visitante no contiene user id',()=>assert.deepEqual(buildAction({...base,decision:'visitor'}),{checkinId:'a',decision:'visitor',reason:'Confirmado en recepción'}));
test('acción de miembro sí contiene user id',()=>assert.equal(buildAction(base).targetUserId,'u1'));
